"""Generates one cannon class per Payload x Pattern pair from src/main/java/dev/megaorbitals/Arsenal.java.

Run from the project root:  python tools/generate_arsenal.py
Existing generated classes are rewritten; hand-written cannons are never touched (names that would
clash with one are skipped and reported).
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "src", "main", "java", "dev", "megaorbitals")
OUT = os.path.join(SRC, "cannons")
MARK = "// Generated by tools/generate_arsenal.py"

text = open(os.path.join(SRC, "Arsenal.java"), encoding="utf-8").read()
pay_block = text[text.index("public enum Payload"):text.index("public final String word, colour")]
pat_block = text[text.index("public enum Pattern"):]
payloads = re.findall(r'^\s{8}([A-Z_]+)\("([^"]+)", "[^"]*", "[^"]*", Material\.\w+, "\w+", \d, (?:true|false), "([^"]+)"', pay_block, re.M)
patterns = re.findall(r'^\s{8}([A-Z_]+)\("([^"]+)", \d+, \d+, [\d.]+, \d+, \d+, "([^"]+)"', pat_block, re.M)
print(len(payloads), "payloads x", len(patterns), "patterns")

hand = set()
for f in os.listdir(OUT):
    if f.endswith(".java"):
        body = open(os.path.join(OUT, f), encoding="utf-8").read()
        if MARK not in body:
            hand.add(f[:-5].lower())

made, clashes = 0, []
for pc, pw, plore in payloads:
    for tc, tw, tlore in patterns:
        cls = re.sub(r"[^A-Za-z0-9]", "", pw) + re.sub(r"[^A-Za-z0-9]", "", tw)
        if cls.lower() in hand:
            clashes.append(cls)
            continue
        src = f"""package dev.megaorbitals.cannons;

{MARK} - edit Arsenal.java and re-run it instead of editing this file.

import dev.megaorbitals.Arsenal.Payload;
import dev.megaorbitals.Arsenal.Pattern;
import dev.megaorbitals.Combo;

/** {pw} {tw}: {plore.lower()}, {tlore}. */
public final class {cls} extends Combo {{
    public {cls}() {{
        super(Payload.{pc}, Pattern.{tc});
    }}
}}
"""
        with open(os.path.join(OUT, cls + ".java"), "w", encoding="utf-8", newline="\n") as fh:
            fh.write(src)
        made += 1
print("wrote", made, "classes")
if clashes:
    print("SKIPPED (name already used by a hand-written cannon):", ", ".join(clashes))
    sys.exit(1)
