package dev.megaorbitals;

import java.io.File;
import java.lang.reflect.Modifier;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;

/**
 * Build-time tool (not used by the server): writes the default configs/<id>.yml for every cannon
 * so they can be bundled in the jar and seen in the project, and optionally CANNONS.md (the full cannon list).
 * Usage: java -cp <classes + paper-api> dev.megaorbitals.ConfigExporter <classesDir> <outputDir> [cannonsMarkdownFile]
 */
public final class ConfigExporter {
    public static void main(String[] args) throws Exception {
        File classes = new File(args[0], "dev/megaorbitals/cannons");
        File out = new File(args[1]);
        out.mkdirs();
        int n = 0;
        File[] files = classes.listFiles((d, name) -> name.endsWith(".class") && !name.contains("$"));
        if (files == null) throw new IllegalStateException("No compiled cannons in " + classes);
        List<Cannon> all = new ArrayList<>();
        for (File f : files) {
            try {
                Class<?> c = Class.forName("dev.megaorbitals.cannons." + f.getName().replace(".class", ""));
                if (!Cannon.class.isAssignableFrom(c) || Modifier.isAbstract(c.getModifiers())) continue;
                Cannon cannon = (Cannon) c.getDeclaredConstructor().newInstance();
                cannon.export(out);
                all.add(cannon);
                n++;
            } catch (Throwable t) {
                System.out.println("FAILED " + f.getName() + ": " + t);
            }
        }
        System.out.println("Exported " + n + " cannon configs to " + out);
        if (args.length > 2) {
            File md = new File(args[2]);
            Files.writeString(md.toPath(), markdown(all), StandardCharsets.UTF_8);
            System.out.println("Wrote cannon list to " + md);
        }
    }

    // ------------------------------------------------------------ CANNONS.md

    private static String plain(String s) {
        return s.replaceAll("&[0-9a-fk-orA-FK-OR]", "").replace("|", "\\|").trim();
    }

    private static String lore(Cannon c) {
        return plain(String.join(" ", c.lore()));
    }

    private static int tierRank(String t) {
        int i = Catalog.TIERS.indexOf(t);
        return i < 0 ? 99 : i;
    }

    private static String markdown(List<Cannon> all) {
        List<Cannon> hand = new ArrayList<>(), arsenal = new ArrayList<>();
        for (Cannon c : all) (c instanceof Combo ? arsenal : hand).add(c);
        StringBuilder sb = new StringBuilder();
        sb.append("# MegaOrbitals cannon list\n\n");
        sb.append("<!-- Generated by ConfigExporter during `mvn package`. Do not edit by hand. -->\n\n");
        sb.append("All **").append(all.size()).append("** cannons: ").append(hand.size()).append(" hand-made cannons and ")
                .append(arsenal.size()).append(" arsenal (payload + pattern) cannons.\n\n");
        sb.append("Fire one with `/orbital <id>` or give it with `/orbitalgive <id>`. ")
                .append("Every cannon's settings are in `plugins/MegaOrbitals/configs/<id>.yml`.\n\n");

        Map<String, int[]> tiers = new LinkedHashMap<>();
        for (String t : Catalog.TIERS) tiers.put(t, new int[1]);
        for (Cannon c : all) tiers.computeIfAbsent(c.tier(), k -> new int[1])[0]++;
        sb.append("| Tier | Cannons |\n|---|---|\n");
        for (Map.Entry<String, int[]> e : tiers.entrySet()) sb.append("| ").append(Catalog.pretty(e.getKey())).append(" | ").append(e.getValue()[0]).append(" |\n");
        sb.append("\n## Contents\n\n");
        Map<String, List<Cannon>> byCat = new TreeMap<>(Comparator.comparingInt((String k) -> {
            int i = Catalog.CATEGORIES.indexOf(k);
            return i < 0 ? 99 : i;
        }).thenComparing(k -> k));
        for (Cannon c : hand) byCat.computeIfAbsent(c.category(), k -> new ArrayList<>()).add(c);
        for (String cat : byCat.keySet())
            sb.append("- [").append(Catalog.pretty(cat)).append("](#").append(cat).append(") (").append(byCat.get(cat).size()).append(")\n");
        sb.append("- [The arsenal](#the-arsenal) (").append(arsenal.size()).append(")\n\n");

        for (Map.Entry<String, List<Cannon>> e : byCat.entrySet()) {
            List<Cannon> list = e.getValue();
            list.sort(Comparator.comparingInt((Cannon c) -> tierRank(c.tier())).thenComparing(Cannon::id));
            sb.append("## ").append(Catalog.pretty(e.getKey())).append("\n\n");
            sb.append("| Cannon | Id | Tier | Breaks blocks | What it does |\n|---|---|---|---|---|\n");
            for (Cannon c : list) {
                sb.append("| ").append(plain(c.name())).append(" | `").append(c.id()).append("` | ").append(Catalog.pretty(c.tier()))
                        .append(" | ").append(c.breaksBlocks() ? "yes" : "no").append(" | ").append(lore(c)).append(" |\n");
            }
            sb.append("\n");
        }

        sb.append("## The arsenal\n\n");
        sb.append("Each arsenal cannon pairs one **payload** (what happens at every impact) with one **pattern** ")
                .append("(where and when the impacts land). The id is the two names joined, in lower case: ")
                .append("Frost + Spiral = `frostspiral`. Every arsenal cannon has the settings `power`, `radius`, `count` and `interval-ticks`.\n\n");
        sb.append("A cannon's tier comes from the payload's weight plus the pattern's weight: ")
                .append("0-1 common, 2-3 rare, 4 epic, 5-6 legendary. Its menu tab is the payload's tab.\n\n");
        sb.append("### Payloads\n\n| Payload | Effect | Menu tab | Weight | Breaks blocks |\n|---|---|---|---|---|\n");
        for (Arsenal.Payload p : Arsenal.Payload.values()) {
            sb.append("| ").append(p.word).append(" | ").append(p.lore).append(" | ").append(Catalog.pretty(p.category))
                    .append(" | ").append(p.weight).append(" | ").append(p.breaks ? "yes" : "no").append(" |\n");
        }
        sb.append("\n### Patterns\n\n| Pattern | How it lands | Weight |\n|---|---|---|\n");
        for (Arsenal.Pattern p : Arsenal.Pattern.values()) {
            sb.append("| ").append(p.word).append(" | ").append(Catalog.pretty(p.lore)).append(" | ").append(p.weight).append(" |\n");
        }
        sb.append("\n### Every arsenal cannon\n\n");
        Map<Arsenal.Payload, List<Combo>> byPayload = new LinkedHashMap<>();
        for (Arsenal.Payload p : Arsenal.Payload.values()) byPayload.put(p, new ArrayList<>());
        for (Cannon c : arsenal) byPayload.get(((Combo) c).payload()).add((Combo) c);
        for (Map.Entry<Arsenal.Payload, List<Combo>> e : byPayload.entrySet()) {
            List<Combo> list = e.getValue();
            if (list.isEmpty()) continue;
            list.sort(Comparator.comparingInt((Combo c) -> c.pattern().ordinal()));
            sb.append("<details><summary><b>").append(e.getKey().word).append("</b> (").append(list.size()).append(")</summary>\n\n");
            sb.append("| Cannon | Id | Tier |\n|---|---|---|\n");
            for (Combo c : list) sb.append("| ").append(plain(c.name())).append(" | `").append(c.id()).append("` | ").append(Catalog.pretty(c.tier())).append(" |\n");
            sb.append("\n</details>\n\n");
        }
        return sb.toString();
    }
}
